#!/usr/bin/env python3
"""Generate one runnable config per (asset, sequence variant) for a given baseline, by scanning
every asset under an eccv_2026_data-style root and discovering which trajectory/illumination/
soil-or-reflectivity combinations actually exist on disk (via inspection_viz.dataset.AssetDataset)
-- instead of hand-writing one example config per sequence, the way every
baselines/configs/*/*-example-config.yaml so far was written.

Each generated file is a single, directly runnable combined config (dataset:/model:/output:, the
same shape every hand-written example config already uses -- see baselines/common/config.py's own
docstring for the two-halves convention this is a shorthand for). `model:` is left empty ({}), so
it takes every default that baseline's own run_sequence.py ModelConfig declares; edit a generated
file directly if you want to override any of them for that one sequence.

This only needs this repo's own light dependencies (pyyaml, inspection_viz -- see requirements.txt)
to discover sequences and write yaml, not any baseline's own heavy ones (torch, cv2, ...), so it
runs fine directly on the host, outside any baseline's container.

Usage:
    python baselines/generate_configs.py --baseline vggt
    python baselines/generate_configs.py --baseline vggt-slam \
        --eccv-root /home/shared/eccv_2026_data --out-dir baselines/configs/vggt-slam/generated

Then, inside that baseline's own container:
    python run_sequence.py ../configs/<baseline>/generated/<asset>_traj=...,illumination=....yaml
"""

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # repo root

from baselines import registry
from inspection_viz.dataset import AssetDataset, Variant

DEFAULT_ECCV_ROOT = Path("/home/shared/eccv_2026_data")


def discover_assets(eccv_root: Path) -> list[AssetDataset]:
    """Every subdirectory of `eccv_root` that's actually an inspection asset (has at least one
    sequence -- AssetDataset's own rgb_dir template matches something under it). eccv_2026_data
    also holds loose files at the same level (colmap_*.sh, upload_script.py, ...); those, and any
    directory with no matching sequences, are skipped with a note rather than erroring.
    """
    assets = []
    for path in sorted(eccv_root.iterdir()):
        if not path.is_dir():
            continue
        try:
            ds = AssetDataset(path)
        except Exception as e:
            print(f"  skipping {path.name}: {e}")
            continue
        if not ds.variants:
            print(f"  skipping {path.name}: no sequences found")
            continue
        assets.append(ds)
    return assets


def variant_slug(variant: Variant) -> str:
    """A filesystem-safe, descriptive name for one variant, e.g. "traj=trendspek,illumination=sunny,soil=low"."""
    return ",".join(f"{k}={v}" for k, v in variant.as_dict().items())


def config_payload(asset_root: Path, variant: Variant) -> dict:
    binds = variant.as_dict()
    return {
        "dataset": {
            "root": str(asset_root),
            "trajectory": binds.get("traj"),
            "illumination": binds.get("illumination"),
            "soil": binds.get("soil"),
            "reflectivity": binds.get("reflectivity"),
            "frame_start": 0,
            "frame_end": None,  # null = to the end
            "frame_stride": 1,
        },
        # Every field defaults -- see baselines/<baseline>/run_sequence.py's own ModelConfig.
        "model": {},
        "output": {
            "method": None,  # null = the baseline's registered name
            "overwrite": False,
            "min_confidence": None,
            "cloud": True,
        },
    }


def write_config(out_path: Path, asset_root: Path, variant: Variant, baseline: str) -> None:
    header = (
        f"# Generated by baselines/generate_configs.py for baseline {baseline!r}.\n"
        f"# Asset: {asset_root}\n"
        "# Every field has a default in run_sequence.py's dataclasses; edit freely -- this file\n"
        "# won't be touched again unless you rerun generate_configs.py and overwrite it.\n\n"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(header + yaml.safe_dump(config_payload(asset_root, variant), sort_keys=False))


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--baseline", required=True, metavar="NAME",
                   help=f"registered baseline to generate configs for; one of: {', '.join(registry.available())}")
    p.add_argument("--eccv-root", type=Path, default=DEFAULT_ECCV_ROOT,
                   help=f"asset root to scan for sequences (default: {DEFAULT_ECCV_ROOT})")
    p.add_argument("--out-dir", type=Path, default=None,
                   help="where to write generated configs "
                        "(default: baselines/configs/<baseline>/generated)")
    args = p.parse_args(argv)

    if args.baseline not in registry.available():
        raise SystemExit(f"unknown baseline {args.baseline!r}; registered: "
                         f"{', '.join(registry.available())}")

    out_dir = args.out_dir or Path(__file__).resolve().parent / "configs" / args.baseline / "generated"

    print(f"scanning {args.eccv_root} for asset sequences ...")
    assets = discover_assets(args.eccv_root)
    if not assets:
        raise SystemExit(f"no assets with sequences found under {args.eccv_root}")

    written = []
    for ds in assets:
        for variant in ds.variants:
            out_path = out_dir / f"{ds.root.name}_{variant_slug(variant)}.yaml"
            write_config(out_path, ds.root, variant, args.baseline)
            written.append(out_path)

    print(f"wrote {len(written)} config(s) to {out_dir}")
    for path in written:
        print(f"  {path}")


if __name__ == "__main__":
    main()
